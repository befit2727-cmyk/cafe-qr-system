export function getDefaultMenuForCafe(cafeSlug: string): MenuItem[] {
  if (DEFAULT_CAFES_DATA[cafeSlug]) {
    return DEFAULT_CAFES_DATA[cafeSlug].menu;
  }
  const foundCafe = DEFAULT_CAFES.find(c => c.slug === cafeSlug);
  if (foundCafe?.template) {
    const templateMatch = Object.values(DEFAULT_CAFES_DATA).find(
      d => d.config.id?.includes(foundCafe.template || "") || d.config.name.toLowerCase().includes(foundCafe.template || "")
    );
    if (templateMatch) return templateMatch.menu;
  }
  return initialMenuItems;
}

